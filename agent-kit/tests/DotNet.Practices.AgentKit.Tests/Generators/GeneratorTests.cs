using DotNet.Practices.AgentKit.Generators;
using DotNet.Practices.AgentKit.Generators.Interfaces;
using DotNet.Practices.AgentKit.Tests.Fixtures;

namespace DotNet.Practices.AgentKit.Tests.Generators;

public class GeneratorTests
{
    private static string Content(IGenerator generator, string path) =>
        generator.Generate(SampleSource.Kit).Single(file => file.RelativePath == path).Content;

    private static IEnumerable<string> Paths(IGenerator generator) => generator.Generate(SampleSource.Kit).Select(file => file.RelativePath);

    [Test]
    public void ClaudeCode_WritesRulesAndAgentsUnderDotClaude()
    {
        Assert.That(Paths(new ClaudeCodeGenerator()), Is.EquivalentTo(new[]
        {
            ".claude/rules/naming.md", ".claude/rules/comments.md", ".claude/agents/researcher.md", ".claude/agents/implementer.md",
        }));
    }

    [Test]
    public void ClaudeCode_ReadOnlyAgent_BlocksWriteToolsInFrontmatter()
    {
        Assert.That(Content(new ClaudeCodeGenerator(), ".claude/agents/researcher.md"), Does.StartWith(
            "---\r\nname: researcher\r\ndescription: Exploración de solo lectura.\r\ntools: Read, Grep, Glob, Bash\r\ndisallowedTools: Edit, Write, NotebookEdit\r\nmodel: sonnet\r\n---\r\n"));
    }

    [Test]
    public void ClaudeCode_WritingAgent_HasNoDisallowedTools()
    {
        Assert.That(Content(new ClaudeCodeGenerator(), ".claude/agents/implementer.md"), Does.Not.Contain("disallowedTools"));
    }

    [Test]
    public void ClaudeCode_GeneratedFile_CarriesTheSourceMarkerAfterFrontmatterAndKeepsTheBody()
    {
        Assert.That(Content(new ClaudeCodeGenerator(), ".claude/agents/researcher.md"), Does.EndWith(
            "---\r\n<!-- generated by agent-kit from source/agents/researcher.md; edit the source, not this file -->\r\n\r\nInvestigas y respondes.\r\n"));
    }

    [Test]
    public void ClaudeCode_Rule_IsTheSourceWithTheMarkerOnTop()
    {
        Assert.That(Content(new ClaudeCodeGenerator(), ".claude/rules/naming.md"), Is.EqualTo(
            "<!-- generated by agent-kit from source/rules/naming.md; edit the source, not this file -->\r\n\r\n# Convención de nombres\r\n\r\nTodo en inglés.\r\n"));
    }

    [Test]
    public void AgentsMd_IsASingleRootFile()
    {
        Assert.That(Paths(new AgentsMdGenerator()), Is.EqualTo(new[] { "AGENTS.md" }));
    }

    [Test]
    public void AgentsMd_ContainsInstructionsEveryRuleAndEveryRoleInOrder()
    {
        var content = Content(new AgentsMdGenerator(), "AGENTS.md");

        Assert.That(new[] { "Lee `CLAUDE.md` primero.", "## Reglas", "# Convención de nombres", "# Comentarios", "## Roles", "### researcher (solo lectura)", "### implementer" }
            .Select(fragment => content.IndexOf(fragment, StringComparison.Ordinal)), Is.Ordered.Ascending.And.All.GreaterThanOrEqualTo(0));
    }

    [Test]
    public void AgentsMd_NestsRuleHeadingsUnderTheRulesSection()
    {
        Assert.That(Content(new AgentsMdGenerator(), "AGENTS.md"), Does.Contain("\r\n### Convención de nombres\r\n").And.Not.Contain("\r\n# Convención de nombres\r\n"));
    }

    [Test]
    public void Cursor_WritesOneMdcPerRuleWithAlwaysApply()
    {
        Assert.That(Content(new CursorGenerator(), ".cursor/rules/naming.mdc"), Does.StartWith("---\r\ndescription: Convención de nombres\r\nalwaysApply: true\r\n---\r\n"));
    }

    [Test]
    public void Cursor_WritesAgentRolesAsAManualRule()
    {
        Assert.That(Content(new CursorGenerator(), ".cursor/rules/agent-roles.mdc"), Does.StartWith("---\r\ndescription: Roles de agente del repositorio\r\nalwaysApply: false\r\n---\r\n").And.Contain("researcher"));
    }

    [Test]
    public void Copilot_WritesASingleInstructionsFileWithRulesOnly()
    {
        var content = Content(new CopilotGenerator(), ".github/copilot-instructions.md");

        Assert.That((content.Contains("# Convención de nombres", StringComparison.Ordinal), content.Contains("researcher", StringComparison.Ordinal)), Is.EqualTo((true, false)));
    }

    [Test]
    public void AllGenerators_UseCrlfOnly()
    {
        var files = new IGenerator[] { new ClaudeCodeGenerator(), new AgentsMdGenerator(), new CursorGenerator(), new CopilotGenerator() }
            .SelectMany(generator => generator.Generate(SampleSource.Kit));

        Assert.That(files.Select(file => file.Content.Replace("\r\n", string.Empty).Contains('\n')), Is.All.False);
    }
}
