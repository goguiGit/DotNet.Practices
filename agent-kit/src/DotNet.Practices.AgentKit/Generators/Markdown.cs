namespace DotNet.Practices.AgentKit.Generators;

internal static class Markdown
{
    public const string NewLine = "\r\n";

    public static string Marker(string sourcePath) =>
        $"<!-- generated by agent-kit from {sourcePath}; edit the source, not this file -->";

    // Pushes every heading down so a rule written as a standalone document nests under a section.
    public static string DemoteHeadings(string body, int levels) =>
        string.Join(NewLine, body.Split(NewLine).Select(line => line.StartsWith('#') ? new string('#', levels) + line : line));
}
